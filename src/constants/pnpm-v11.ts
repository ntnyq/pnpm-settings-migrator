/**
 * Lookup used to exclude machine and invocation settings from workspace fields.
 */
const refusedProjectSettings = new Set(PNPM_PROJECT_REFUSED_SETTINGS)

/**
 * Settings accepted for migration to a pnpm v11 workspace.
 */
export const PNPM_V11_WORKSPACE_SETTINGS_FIELDS = pnpmV11WorkspaceFields.filter(
  field => !refusedProjectSettings.has(field),
)

